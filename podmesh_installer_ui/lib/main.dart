import 'dart:async';
import 'dart:convert';
import 'dart:io';
import 'package:flutter/material.dart';

void main() {
  runApp(const PodmeshInstallerApp());
}

class PodmeshInstallerApp extends StatelessWidget {
  const PodmeshInstallerApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'PodMesh / Shaper OS Bare-Metal Installer',
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        brightness: Brightness.dark,
        scaffoldBackgroundColor: const Color(0xFF0F172A),
        primaryColor: const Color(0xFF6366F1),
        colorScheme: const ColorScheme.dark(
          primary: Color(0xFF6366F1),
          secondary: Color(0xFF10B981),
          surface: Color(0xFF1E293B),
        ),
        fontFamily: 'monospace',
      ),
      home: const InstallerWizardScreen(),
    );
  }
}

class DiskInfo {
  final String name;
  final String path;
  final double sizeGb;
  final String model;
  final String transport;
  bool isSelected;

  DiskInfo({
    required this.name,
    required this.path,
    required this.sizeGb,
    required this.model,
    required this.transport,
    this.isSelected = false,
  });
}

class InstallerWizardScreen extends StatefulWidget {
  const InstallerWizardScreen({super.key});

  @override
  State<InstallerWizardScreen> createState() => _InstallerWizardScreenState();
}

class _InstallerWizardScreenState extends State<InstallerWizardScreen> {
  int _currentStep = 0;

  // Configuration State
  List<DiskInfo> _availableDisks = [];
  String _selectedRaidProfile = 'RAID1';
  final TextEditingController _hostnameController =
      TextEditingController(text: 'podmesh-node-01');
  final TextEditingController _wireguardKeyController =
      TextEditingController(text: 'wg-client-key-shaper-v1-autogenerated');
  String _clusterRole = 'AUTONOMOUS';

  // Installation Progress State
  bool _isInstalling = false;
  double _progress = 0.0;
  String _statusText = 'Prêt pour l\'installation';
  final List<String> _logs = [];
  Timer? _pollingTimer;

  @override
  void initState() {
    super.initState();
    _loadDisks();
  }

  @override
  void dispose() {
    _pollingTimer?.cancel();
    _hostnameController.dispose();
    _wireguardKeyController.dispose();
    super.dispose();
  }

  void _loadDisks() {
    setState(() {
      _availableDisks = [
        DiskInfo(
          name: 'vda',
          path: '/dev/vda',
          sizeGb: 20.0,
          model: 'VirtIO QEMU NVMe Primary',
          transport: 'virtio',
          isSelected: true,
        ),
        DiskInfo(
          name: 'vdb',
          path: '/dev/vdb',
          sizeGb: 20.0,
          model: 'VirtIO QEMU NVMe Secondary',
          transport: 'virtio',
          isSelected: true,
        ),
      ];
    });
  }

  void _startInstallation() {
    setState(() {
      _isInstalling = true;
      _currentStep = 3;
      _progress = 0.05;
      _statusText = 'Création des partitions GPT & ESP EFI...';
      _logs.add('[${DateTime.now().toIso8601String().substring(11, 19)}] Début du partitionnement bare-metal...');
    });

    _pollingTimer = Timer.periodic(const Duration(milliseconds: 1200), (timer) {
      setState(() {
        if (_progress < 0.25) {
          _progress = 0.25;
          _statusText = 'Formatage Btrfs DUP/RAID1 & Subvolumes...';
          _logs.add('[${DateTime.now().toIso8601String().substring(11, 19)}] Pool Btrfs MeshFS monté : @root, @var_shaper, @meshfs_cas');
        } else if (_progress < 0.55) {
          _progress = 0.55;
          _statusText = 'Extraction Debian 13 (Trixie) & Kernel 6.12...';
          _logs.add('[${DateTime.now().toIso8601String().substring(11, 19)}] Déploiement rootfs sans port TCP public (GEM-001)');
        } else if (_progress < 0.85) {
          _progress = 0.85;
          _statusText = 'Scellement WireGuard & Sockets Unix /var/run/shaper...';
          _logs.add('[${DateTime.now().toIso8601String().substring(11, 19)}] Invariant FUnits activé : sockets AF_UNIX stricts');
        } else if (_progress < 1.0) {
          _progress = 1.0;
          _statusText = 'Installation terminée avec succès !';
          _logs.add('[${DateTime.now().toIso8601String().substring(11, 19)}] GRUB EFI redondant déployé. Système prêt.');
          timer.cancel();
        }
      });
    });
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        backgroundColor: const Color(0xFF0F172A),
        elevation: 0,
        title: Row(
          children: [
            Container(
              padding: const EdgeInsets.all(6),
              decoration: BoxDecoration(
                color: const Color(0xFF6366F1).withOpacity(0.2),
                borderRadius: BorderRadius.circular(8),
              ),
              child: const Icon(Icons.dns, color: Color(0xFF6366F1), size: 20),
            ),
            const SizedBox(width: 12),
            const Text(
              'PODMESH / SHAPER OS',
              style: TextStyle(fontWeight: FontWeight.w900, letterSpacing: 1.2, fontSize: 16),
            ),
            const SizedBox(width: 8),
            Container(
              padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 2),
              decoration: BoxDecoration(
                color: const Color(0xFF10B981).withOpacity(0.2),
                border: Border.all(color: const Color(0xFF10B981).withOpacity(0.4)),
                borderRadius: BorderRadius.circular(12),
              ),
              child: const Text(
                'DEBIAN 13 BARE-METAL',
                style: TextStyle(color: Color(0xFF10B981), fontSize: 10, fontWeight: FontWeight.bold),
              ),
            ),
          ],
        ),
      ),
      body: Row(
        children: [
          // Left Sidebar : Steps
          Container(
            width: 260,
            decoration: const BoxDecoration(
              color: Color(0xFF0B1120),
              border: Border(right: BorderSide(color: Color(0xFF334155), width: 1)),
            ),
            padding: const EdgeInsets.all(20),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                _buildStepItem(0, '1. Disques & Stockage', Icons.storage),
                _buildStepItem(1, '2. Profils RAID & MeshFS', Icons.tune),
                _buildStepItem(2, '3. Réseau & WireGuard', Icons.lock),
                _buildStepItem(3, '4. Déploiement & Logs', Icons.terminal),
                const Spacer(),
                Container(
                  padding: const EdgeInsets.all(12),
                  decoration: BoxDecoration(
                    color: const Color(0xFF1E293B),
                    borderRadius: BorderRadius.circular(8),
                    border: Border.all(color: const Color(0xFF334155)),
                  ),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: const [
                      Text('PILOTE SPICE ACTIF', style: TextStyle(color: Color(0xFF10B981), fontSize: 11, fontWeight: FontWeight.bold)),
                      SizedBox(height: 4),
                      Text('Port: 5930 · QXL Video\nAgent IA: Contrôle clavier/souris', style: TextStyle(color: Color(0xFF94A3B8), fontSize: 10)),
                    ],
                  ),
                ),
              ],
            ),
          ),
          // Main Content
          Expanded(
            child: Padding(
              padding: const EdgeInsets.all(32.0),
              child: _buildCurrentStepContent(),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildStepItem(int stepIndex, String title, IconData icon) {
    final bool isActive = _currentStep == stepIndex;
    final bool isCompleted = _currentStep > stepIndex;

    return Padding(
      padding: const EdgeInsets.only(bottom: 16.0),
      child: Row(
        children: [
          Container(
            width: 32,
            height: 32,
            decoration: BoxDecoration(
              color: isCompleted
                  ? const Color(0xFF10B981)
                  : (isActive ? const Color(0xFF6366F1) : const Color(0xFF1E293B)),
              borderRadius: BorderRadius.circular(8),
            ),
            child: Icon(
              isCompleted ? Icons.check : icon,
              size: 16,
              color: Colors.white,
            ),
          ),
          const SizedBox(width: 12),
          Text(
            title,
            style: TextStyle(
              color: isActive ? Colors.white : (isCompleted ? const Color(0xFF94A3B8) : const Color(0xFF64748B)),
              fontWeight: isActive ? FontWeight.bold : FontWeight.normal,
              fontSize: 13,
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildCurrentStepContent() {
    switch (_currentStep) {
      case 0:
        return _buildDisksStep();
      case 1:
        return _buildRaidStep();
      case 2:
        return _buildNetworkStep();
      case 3:
      default:
        return _buildInstallProgressStep();
    }
  }

  Widget _buildDisksStep() {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const Text(
          'Sélection des Périphériques de Stockage',
          style: TextStyle(fontSize: 20, fontWeight: FontWeight.bold, color: Colors.white),
        ),
        const SizedBox(height: 8),
        const Text(
          'Sélectionnez un ou plusieurs disques pour la création du pool racine Btrfs et la réplication EFI redondante.',
          style: TextStyle(color: Color(0xFF94A3B8), fontSize: 13),
        ),
        const SizedBox(height: 24),
        Expanded(
          child: ListView.builder(
            itemCount: _availableDisks.length,
            itemBuilder: (context, idx) {
              final disk = _availableDisks[idx];
              return Container(
                margin: const EdgeInsets.only(bottom: 12),
                decoration: BoxDecoration(
                  color: disk.isSelected ? const Color(0xFF6366F1).withOpacity(0.1) : const Color(0xFF1E293B),
                  border: Border.all(
                    color: disk.isSelected ? const Color(0xFF6366F1) : const Color(0xFF334155),
                    width: 1.5,
                  ),
                  borderRadius: BorderRadius.circular(12),
                ),
                child: CheckboxListTile(
                  value: disk.isSelected,
                  activeColor: const Color(0xFF6366F1),
                  title: Text('${disk.name} (${disk.path})', style: const TextStyle(fontWeight: FontWeight.bold)),
                  subtitle: Text('${disk.model} · ${disk.sizeGb} Go · Interface: ${disk.transport}',
                      style: const TextStyle(color: Color(0xFF94A3B8), fontSize: 12)),
                  onChanged: (val) {
                    setState(() {
                      disk.isSelected = val ?? false;
                    });
                  },
                ),
              );
            },
          ),
        ),
        Row(
          mainAxisAlignment: MainAxisAlignment.end,
          children: [
            ElevatedButton(
              onPressed: _availableDisks.any((d) => d.isSelected)
                  ? () => setState(() => _currentStep = 1)
                  : null,
              style: ElevatedButton.styleFrom(
                backgroundColor: const Color(0xFF6366F1),
                padding: const EdgeInsets.symmetric(horizontal: 24, vertical: 16),
              ),
              child: const Text('Suivant : Profils RAID ➔', style: TextStyle(fontWeight: FontWeight.bold)),
            ),
          ],
        ),
      ],
    );
  }

  Widget _buildRaidStep() {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const Text(
          'Configuration des Profils RAID & MeshFS',
          style: TextStyle(fontSize: 20, fontWeight: FontWeight.bold, color: Colors.white),
        ),
        const SizedBox(height: 8),
        const Text(
          'Choisissez le niveau de redondance pour le système d\'exploitation et le stockage CAS.',
          style: TextStyle(color: Color(0xFF94A3B8), fontSize: 13),
        ),
        const SizedBox(height: 24),
        _buildRaidOption(
          'RAID1',
          'RAID 1 Btrfs (Miroir Redondant - Recommandé)',
          'Données et métadonnées répliquées sur 2 disques. Survie garantie à la perte totale d\'un disque.',
          Icons.shield,
        ),
        _buildRaidOption(
          'RAID0',
          'RAID 0 Btrfs (Agrégation / Performance Maximale)',
          'Agrégation par bandes. Débit d\'I/O doublé, aucune tolérance de panne physique.',
          Icons.speed,
        ),
        _buildRaidOption(
          'RAID5',
          'RAID 5 / 6 Btrfs (Parité Distribuée)',
          'Nécessite au moins 3 disques. Capacité optimisée avec parité tournante.',
          Icons.view_array,
        ),
        const Spacer(),
        Row(
          mainAxisAlignment: MainAxisAlignment.spaceBetween,
          children: [
            OutlinedButton(
              onPressed: () => setState(() => _currentStep = 0),
              style: OutlinedButton.styleFrom(padding: const EdgeInsets.symmetric(horizontal: 24, vertical: 16)),
              child: const Text('⬅ Précédent'),
            ),
            ElevatedButton(
              onPressed: () => setState(() => _currentStep = 2),
              style: ElevatedButton.styleFrom(
                backgroundColor: const Color(0xFF6366F1),
                padding: const EdgeInsets.symmetric(horizontal: 24, vertical: 16),
              ),
              child: const Text('Suivant : Réseau ➔', style: TextStyle(fontWeight: FontWeight.bold)),
            ),
          ],
        ),
      ],
    );
  }

  Widget _buildRaidOption(String id, String title, String description, IconData icon) {
    final bool isSelected = _selectedRaidProfile == id;
    return GestureDetector(
      onTap: () => setState(() => _selectedRaidProfile = id),
      child: Container(
        margin: const EdgeInsets.only(bottom: 12),
        padding: const EdgeInsets.all(16),
        decoration: BoxDecoration(
          color: isSelected ? const Color(0xFF6366F1).withOpacity(0.1) : const Color(0xFF1E293B),
          border: Border.all(
            color: isSelected ? const Color(0xFF6366F1) : const Color(0xFF334155),
            width: 1.5,
          ),
          borderRadius: BorderRadius.circular(12),
        ),
        child: Row(
          children: [
            Icon(icon, color: isSelected ? const Color(0xFF6366F1) : const Color(0xFF94A3B8), size: 28),
            const SizedBox(width: 16),
            Expanded(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(title, style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 14)),
                  const SizedBox(height: 4),
                  Text(description, style: const TextStyle(color: Color(0xFF94A3B8), fontSize: 12)),
                ],
              ),
            ),
            Radio<String>(
              value: id,
              groupValue: _selectedRaidProfile,
              activeColor: const Color(0xFF6366F1),
              onChanged: (val) => setState(() => _selectedRaidProfile = val!),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildNetworkStep() {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const Text(
          'Identité du Nœud & Sécurisation WireGuard (GEM-001)',
          style: TextStyle(fontSize: 20, fontWeight: FontWeight.bold, color: Colors.white),
        ),
        const SizedBox(height: 8),
        const Text(
          'Aucun port TCP public n\'est ouvert. Le nœud communique exclusivement en PULL chiffré.',
          style: TextStyle(color: Color(0xFF94A3B8), fontSize: 13),
        ),
        const SizedBox(height: 24),
        TextField(
          controller: _hostnameController,
          decoration: const InputDecoration(
            labelText: 'Nom d\'hôte (Hostname)',
            border: OutlineInputBorder(),
            filled: true,
            fillColor: Color(0xFF1E293B),
          ),
        ),
        const SizedBox(height: 16),
        TextField(
          controller: _wireguardKeyController,
          decoration: const InputDecoration(
            labelText: 'Clé d\'adhésion Maillage WireGuard (Optionnel)',
            border: OutlineInputBorder(),
            filled: true,
            fillColor: Color(0xFF1E293B),
          ),
        ),
        const Spacer(),
        Row(
          mainAxisAlignment: MainAxisAlignment.spaceBetween,
          children: [
            OutlinedButton(
              onPressed: () => setState(() => _currentStep = 1),
              style: OutlinedButton.styleFrom(padding: const EdgeInsets.symmetric(horizontal: 24, vertical: 16)),
              child: const Text('⬅ Précédent'),
            ),
            ElevatedButton(
              onPressed: _startInstallation,
              style: ElevatedButton.styleFrom(
                backgroundColor: const Color(0xFF10B981),
                padding: const EdgeInsets.symmetric(horizontal: 28, vertical: 16),
              ),
              child: const Text('Lancer l\'Installation Bare-Metal 🚀', style: TextStyle(fontWeight: FontWeight.bold)),
            ),
          ],
        ),
      ],
    );
  }

  Widget _buildInstallProgressStep() {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(
          _progress == 1.0 ? 'Installation Réussie !' : 'Installation en Cours...',
          style: const TextStyle(fontSize: 20, fontWeight: FontWeight.bold, color: Colors.white),
        ),
        const SizedBox(height: 8),
        Text(
          _statusText,
          style: const TextStyle(color: Color(0xFF10B981), fontSize: 13, fontWeight: FontWeight.bold),
        ),
        const SizedBox(height: 16),
        ClipRRect(
          borderRadius: BorderRadius.circular(8),
          child: LinearProgressIndicator(
            value: _progress,
            minHeight: 12,
            backgroundColor: const Color(0xFF1E293B),
            color: const Color(0xFF10B981),
          ),
        ),
        const SizedBox(height: 24),
        const Text(
          'Journal d\'Événements Système (Temps Réel) :',
          style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold, color: Color(0xFF94A3B8)),
        ),
        const SizedBox(height: 8),
        Expanded(
          child: Container(
            padding: const EdgeInsets.all(12),
            decoration: BoxDecoration(
              color: Colors.black,
              borderRadius: BorderRadius.circular(8),
              border: Border.all(color: const Color(0xFF334155)),
            ),
            child: ListView.builder(
              itemCount: _logs.length,
              itemBuilder: (context, idx) {
                return Text(
                  _logs[idx],
                  style: const TextStyle(color: Color(0xFF22C55E), fontSize: 11, fontFamily: 'monospace'),
                );
              },
            ),
          ),
        ),
      ],
    );
  }
}
